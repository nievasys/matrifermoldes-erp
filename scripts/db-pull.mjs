// Regenerates src/lib/server/db/schema.ts from the database (schema "app" only).
// The output is generated code: never edit it by hand, change a SQL migration and rerun `pnpm db:pull`.
import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync, writeFileSync } from 'node:fs';

const OUT = '.drizzle';
const TARGET = 'src/lib/server/db/schema.ts';

rmSync(OUT, { recursive: true, force: true });
execFileSync('pnpm', ['exec', 'drizzle-kit', 'pull'], { stdio: 'inherit' });

let source = readFileSync(`${OUT}/schema.ts`, 'utf8');

// Only schema "app" is introspected, so foreign keys into auth.users point at a table that is
// not part of the generated file. They stay enforced by PostgreSQL; drop them from the typings.
const crossSchemaFk = /\s*foreignKey\(\{[^}]*foreignColumns: \[users\.id\][^}]*\}\),?/g;
source = source.replace(crossSchemaFk, '');

if (/\busers\./.test(source)) {
	throw new Error(`${OUT}/schema.ts still references a table outside schema "app"`);
}

const header =
	'// GENERATED by `pnpm db:pull` (drizzle-kit pull). Do not edit by hand.\n' +
	'// Source of truth: supabase/migrations/*.sql\n\n';

writeFileSync(TARGET, header + source);
rmSync(OUT, { recursive: true, force: true });
console.log(`Wrote ${TARGET}`);
